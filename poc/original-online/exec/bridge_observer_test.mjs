import assert from 'node:assert/strict';
import {observeBridgeOpen} from './bridge_observer.mjs';

const memory = new WebAssembly.Memory({initial: 1, maximum: 1, shared: true});
const heap = new Uint8Array(memory.buffer);
heap.set(new TextEncoder().encode('127.0.0.1'), 32);
const before = new Uint8Array(heap), records = [], calls = [];
const sentinel = {}, thrown = new Error('actual bridge failure');
const bridge = {lastError: 14, open(...args) {calls.push({receiver: this, args}); if(args[2] === 13)throw thrown; return args[2] === 443 ? sentinel : 0;}};
const Module = {HEAPU8: heap, originalOnlineBridge: bridge};
observeBridgeOpen(Module, value => records.push(value));
assert.equal(bridge.open(32, 9, 443, 0), sentinel);
assert.equal(records[0].address, '127.0.0.1');
assert.equal(records[0].shared, true);
assert.equal(records[0].heapLength, 65536);
assert.deepEqual(calls[0], {receiver: bridge, args: [32, 9, 443, 0]});
assert.equal(bridge.open(65530, 9, 0, 0), 0);
assert.equal(records[1].spanValid, false);
assert.equal(records[1].portValid, false);
assert.equal(records[1].addressBytes, undefined);
assert.equal(bridge.open(32, 254, 0, 0), 0);
assert.equal(records[2].addressBytes, undefined);
assert.throws(() => bridge.open(32, 9, 13, 0), error => error === thrown);
assert.equal(records[3].thrown.message, thrown.message);
assert.equal(bridge.open(32, 9, 443, 0), sentinel);
assert.equal(records.length, 4); assert.equal(calls.length, 5);
assert.deepEqual(heap, before);
assert.throws(() => observeBridgeOpen(Module), /unobserved/);
const throwingEmitter = {HEAPU8: heap, originalOnlineBridge: {open: () => 7, lastError: 0}};
observeBridgeOpen(throwingEmitter, () => {throw new Error('diagnostic output unavailable');});
assert.equal(throwingEmitter.originalOnlineBridge.open(32, 9, 443, 0), 7);
const brokenError = {get name() {throw new Error('diagnostic getter');}};
const failingDiagnostics = {HEAPU8: heap, originalOnlineBridge: {open: () => {throw brokenError;}}};
observeBridgeOpen(failingDiagnostics);
assert.throws(() => failingDiagnostics.originalOnlineBridge.open(32, 9, 443, 0), error => error === brokenError);
const failingResult = {HEAPU8: heap, originalOnlineBridge: {open: () => 9, get lastError() {throw new Error('diagnostic getter');}}};
observeBridgeOpen(failingResult);
assert.equal(failingResult.originalOnlineBridge.open(32, 9, 443, 0), 9);
const invalid = {HEAPU8: new Uint8Array([255]), originalOnlineBridge: {open: () => 0, lastError: 14}};
const rejected = []; observeBridgeOpen(invalid, row => rejected.push(row));
assert.equal(invalid.originalOnlineBridge.open(0, 1, 443, 0), 0);
assert.equal(rejected[0].decodeError.name, 'TypeError');
console.log('Bridge observer: actual arguments/receiver/result/throw and memory preserved; invalid spans/UTF8, emission failure and four-record bound passed.');
